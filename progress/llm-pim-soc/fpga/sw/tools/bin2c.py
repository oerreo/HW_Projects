#!/usr/bin/env python3
"""Convert binary files into one C source with const byte arrays.

    python3 -I bin2c.py OUT.c FILE:SYMBOL [FILE:SYMBOL ...]
    python3 -I bin2c.py --check OUT.c FILE:SYMBOL [...]   # parse OUT.c back, compare

Without arguments the same values come from the environment (keeps file names off
the process list on the shared server): BIN2C_OUT, BIN2C_IN (space separated
FILE:SYMBOL list), BIN2C_CHECK=1.

Each SYMBOL gets `const unsigned char SYMBOL[]` (64-byte aligned, so float data in
the image is naturally aligned) and `const uint32_t SYMBOL_len`. The output is a
derived copy of the input files: it is generated into fpga/sw/gen/ and never
committed (model weights and tokenizers stay out of the repository).
"""
import hashlib
import re
import sys


def parse_specs(specs):
    out = []
    for s in specs:
        path, sep, sym = s.rpartition(":")
        if not sep or not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", sym):
            raise SystemExit(f"bad FILE:SYMBOL '{s}'")
        out.append((path, sym))
    return out


def write(out_path, specs):
    parts = ["/* Generated by fpga/sw/tools/bin2c.py. Do not edit, do not commit. */\n",
             "#include <stdint.h>\n"]
    for path, sym in specs:
        data = open(path, "rb").read()
        parts.append(f"/* {sym}: {len(data)} bytes, sha256 {hashlib.sha256(data).hexdigest()} */\n")
        parts.append(f"__attribute__((aligned(64))) const unsigned char {sym}[{max(len(data), 1)}] = {{\n")
        for i in range(0, len(data), 24):
            parts.append(",".join(str(b) for b in data[i:i + 24]) + ",\n")
        if not data:
            parts.append("0\n")
        parts.append("};\n")
        parts.append(f"const uint32_t {sym}_len = {len(data)}u;\n")
    with open(out_path, "w") as f:
        f.write("".join(parts))


def read_back(out_path):
    text = open(out_path).read()
    arrays = {}
    for m in re.finditer(r"const unsigned char (\w+)\[\d+\] = \{\n(.*?)\};\n"
                         r"const uint32_t \1_len = (\d+)u;", text, re.S):
        sym, body, n = m.group(1), m.group(2), int(m.group(3))
        vals = [int(v) for v in re.findall(r"\d+", body)]
        arrays[sym] = bytes(vals[:n]) if n else b""
        if n and len(vals) != n:
            raise SystemExit(f"{sym}: {len(vals)} values for length {n}")
    return arrays


def main(argv):
    import os
    if not argv and os.environ.get("BIN2C_OUT"):
        argv = ([] if os.environ.get("BIN2C_CHECK") != "1" else ["--check"]) + \
            [os.environ["BIN2C_OUT"]] + os.environ.get("BIN2C_IN", "").split()
    check = False
    if argv and argv[0] == "--check":
        check = True
        argv = argv[1:]
    if len(argv) < 2:
        raise SystemExit(__doc__)
    out_path, specs = argv[0], parse_specs(argv[1:])
    if not check:
        write(out_path, specs)
        print(f"bin2c: wrote {out_path} ({len(specs)} arrays)")
        return 0
    arrays = read_back(out_path)
    bad = 0
    for path, sym in specs:
        data = open(path, "rb").read()
        ok = arrays.get(sym) == data
        bad += not ok
        print(f"bin2c check {sym} bytes={len(data)} result={'PASS' if ok else 'FAIL'}")
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
