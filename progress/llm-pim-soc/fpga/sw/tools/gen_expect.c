/*
 * PC generator of the expected-value header for the board program
 * (fpga/sw/expect/exp_m*.h). Uses the golden PC driver of model/tools/io.c
 * (bundle_load, bundle_step, H format table) and the unmodified model/src library,
 * so the board driver (src/bench.c) is checked against an independent driver.
 *
 * Settings come from a config file (env CFG) or environment variables of the same
 * name, never from the command line:
 *   ck, tk   checkpoint and tokenizer files
 *   pf, pi   prompt file and prompt line index
 *   steps    positions to generate (0: seq_len)
 *   vars     variants, e.g. F,Qg,HD (Qr/Qg as model/tools/io.c, H names from its table)
 *   name     model label ("260K"), sym C symbol (EXP_M1), out header path
 *   corrupt  1: write deliberately wrong values (negative test only)
 */
#include <stddef.h>
#include <stdlib.h>
#include <string.h>
#include "io.h"
#include "lmhash.h"

static FILE *O;

static void arr_i32(const char *type, const char *sym, const char *suf, const int32_t *v, int n) {
  int i;
  fprintf(O, "static const %s %s_%s[%d] = {", type, sym, suf, n > 0 ? n : 1);
  for (i = 0; i < n; i++) fprintf(O, "%s%d", i == 0 ? "\n  " : i % 16 ? ", " : ",\n  ", (int)v[i]);
  if (n == 0) fprintf(O, "0");
  fprintf(O, "};\n");
}

static void arr_u32(const char *sym, const char *suf, const uint32_t *v, int n) {
  int i;
  fprintf(O, "static const uint32_t %s_%s[%d] = {", sym, suf, n);
  for (i = 0; i < n; i++) fprintf(O, "%s0x%08xu", i == 0 ? "\n  " : i % 8 ? ", " : ",\n  ", (unsigned)v[i]);
  fprintf(O, "};\n");
}

static void cstr(const char *s) {
  fputc('"', O);
  for (; *s; s++) {
    unsigned char ch = (unsigned char)*s;
    if (ch == '"' || ch == '\\') fprintf(O, "\\%c", ch);
    else if (ch < 0x20 || ch >= 0x7F) fprintf(O, "\\%03o", ch);
    else fputc(ch, O);
  }
  fputc('"', O);
}

int main(void) {
  bundle_t b;
  char **pr;
  const char *sym, *name;
  int np, pi, steps, nt, vi, i, corrupt, *tok;
  int32_t *ptok, *am[MAXV];
  uint32_t *lh[MAXV], wh[MAXV];
  int hsz, rope_v = -1, V;
  if (cfg_load()) fprintf(stderr, "gen_expect: no config file, environment only\n");
  sym = cfg_s("sym", "EXP_M1");
  name = cfg_s("name", "260K");
  pi = (int)cfg_i("pi", 1);
  corrupt = (int)cfg_i("corrupt", 0);
  if (bundle_load(&b, cfg_s("ck", ""), cfg_s("tk", ""), cfg_s("vars", "F,Qg,HD"))) {
    fprintf(stderr, "gen_expect: load failed\n");
    return 1;
  }
  if (b.nv > 4) {
    fprintf(stderr, "gen_expect: at most 4 variants\n");
    return 1;
  }
  V = b.c.vocab_size;
  steps = (int)cfg_i("steps", 0);
  if (steps <= 0 || steps > b.c.seq_len) steps = b.c.seq_len;
  np = io_prompts(cfg_s("pf", ""), &pr);
  if (np <= pi) {
    fprintf(stderr, "gen_expect: prompt %d missing\n", pi);
    return 1;
  }
  tok = malloc(sizeof(int) * (strlen(pr[pi]) + 3));
  lm_tok_encode(&b.tok, pr[pi], 1, 0, tok, &nt);
  ptok = malloc(sizeof(int32_t) * (size_t)nt);
  for (i = 0; i < nt; i++) ptok[i] = tok[i];

  for (vi = 0; vi < b.nv; vi++) {
    variant_t *v = &b.v[vi];
    int pos, cur = tok[0];
    float *lf = malloc(sizeof(float) * (size_t)V);
    am[vi] = malloc(sizeof(int32_t) * (size_t)steps);
    lh[vi] = malloc(sizeof(uint32_t) * (size_t)steps);
    for (pos = 0; pos < steps; pos++) {
      int a = bundle_step(&b, vi, cur, pos, lf, NULL);
      const void *lg = v->kind == VK_H ? (const void *)v->hs.logits
                       : v->kind == VK_F ? (const void *)v->fs.logits
                                         : (const void *)v->qs.f.logits;
      if (a < 0) {
        fprintf(stderr, "gen_expect: forward error %s pos %d\n", v->name, pos);
        return 1;
      }
      am[vi][pos] = a;
      lh[vi][pos] = h_fnv(H_INIT, lg, 4u * (size_t)V);
      cur = pos + 1 < nt ? tok[pos + 1] : a;
    }
    free(lf);
    wh[vi] = v->kind == VK_Q ? h_qweights(&v->qw, &b.c) : v->kind == VK_H ? h_hweights(&v->hw, &b.c) : 0;
    if (v->kind == VK_H && rope_v < 0) rope_v = vi;
    if (v->kind == VK_H) {
      /* the exported integer fields must reproduce the whole lm_hfmt_t */
      lm_hfmt_t r;
      size_t o = offsetof(lm_hfmt_t, act_mode);
      memset(&r, 0, sizeof(r));
      r.act_mode = v->hf.act_mode; r.wgs = v->hf.wgs; r.exp_bits = v->hf.exp_bits;
      r.sig_bits = v->hf.sig_bits; r.kv16 = v->hf.kv16; r.kbits = v->hf.kbits;
      r.vbits = v->hf.vbits; r.win = v->hf.win;
      if (memcmp((char *)&r + o, (char *)&v->hf + o, sizeof(r) - o)) {
        fprintf(stderr, "gen_expect: lm_hfmt_t has fields unknown to gen_expect (%s)\n", v->name);
        return 1;
      }
    }
  }
  if (corrupt) { /* negative test: one wrong token in variant 0, one wrong hash in the last */
    am[0][nt + 2] = (am[0][nt + 2] + 1) % V;
    lh[b.nv - 1][nt + 3] ^= 1u;
  }

  O = fopen(cfg_s("out", "exp.h"), "w");
  if (!O) return 1;
  hsz = b.c.dim / b.c.n_heads;
  fprintf(O, "/* Generated by fpga/sw/tools/gen_expect.c. Do not edit. */\n");
  fprintf(O, "/* model %s, prompt line %d, steps %d, vars %s%s */\n", name, pi, steps,
          cfg_s("vars", "F,Qg,HD"), corrupt ? ", CORRUPTED (negative test)" : "");
  fprintf(O, "#include <stdint.h>\n#include \"expect.h\"\n");
  arr_i32("int32_t", sym, "ptok", ptok, nt);
  for (vi = 0; vi < b.nv; vi++) {
    char s[16];
    sprintf(s, "tok%d", vi);
    arr_i32("int32_t", sym, s, am[vi], steps);
    sprintf(s, "lh%d", vi);
    arr_u32(sym, s, lh[vi], steps);
  }
  {
    int nr = rope_v >= 0 ? b.c.seq_len * hsz : 0;
    int32_t *r32 = malloc(sizeof(int32_t) * (size_t)(nr > 0 ? nr : 1));
    uint32_t rh = rope_v >= 0 ? h_fnv(H_INIT, b.v[rope_v].hw.rope, sizeof(int16_t) * (size_t)nr) : 0;
    for (i = 0; i < nr; i++) r32[i] = b.v[rope_v].hw.rope[i];
    arr_i32("int16_t", sym, "rope", r32, nr);
    fprintf(O, "const exp_model_t %s = {\n", sym);
    fprintf(O, "  .model = \"%s\", .dim = %d, .hidden = %d, .layers = %d, .heads = %d,\n", name,
            b.c.dim, b.c.hidden_dim, b.c.n_layers, b.c.n_heads);
    fprintf(O, "  .kv_heads = %d, .vocab = %d, .seq_len = %d,\n", b.c.n_kv_heads, V, b.c.seq_len);
    fprintf(O, "  .ck_len = %luu, .ck_hash = 0x%08xu, .tk_len = %luu, .tk_hash = 0x%08xu,\n",
            (unsigned long)b.ckn, (unsigned)h_fnv(H_INIT, b.ck, b.ckn), (unsigned long)b.tkn,
            (unsigned)h_fnv(H_INIT, b.tk, b.tkn));
    fprintf(O, "  .prompt = ");
    cstr(pr[pi]);
    fprintf(O, ", .pidx = %d, .nptok = %d, .ptok = %s_ptok, .steps = %d,\n", pi, nt, sym, steps);
    fprintf(O, "  .rope = %s_rope, .rope_n = %d, .rope_hash = 0x%08xu, .corrupt = %d,\n", sym, nr,
            (unsigned)rh, corrupt);
    fprintf(O, "  .nvar = %d,\n  .var = {\n", b.nv);
    for (vi = 0; vi < b.nv; vi++) {
      variant_t *v = &b.v[vi];
      const lm_hfmt_t *f = &v->hf;
      int kind = v->kind == VK_F ? 0 : v->kind == VK_Q ? 1 : 2;
      fprintf(O, "    {.name = \"%s\", .kind = %d, .qgs = %d,\n", v->name, kind,
              v->kind == VK_Q ? v->qw.gs_target : 0);
      if (kind == 2)
        fprintf(O, "     .hf = {%d, %d, %d, %d, %d, %d, %d, %d},\n", f->act_mode, f->wgs, f->exp_bits,
                f->sig_bits, f->kv16, f->kbits, f->vbits, f->win);
      fprintf(O, "     .tok = %s_tok%d, .lh = %s_lh%d, .whash = 0x%08xu},\n", sym, vi, sym, vi,
              (unsigned)wh[vi]);
    }
    fprintf(O, "  }};\n");
    free(r32);
  }
  fclose(O);
  printf("gen_expect: %s %s steps=%d nptok=%d vars=%d%s\n", sym, name, steps, nt, b.nv,
         corrupt ? " corrupt" : "");
  return 0;
}
