/*
 * Generates src/tabs.c: the constant LUTs of the H kernels. The output is committed
 * so that every platform (PC, ARM, RTL ROM) uses the same integers; libm is used
 * only here, offline.
 * Build and run: make tabs
 */
#include <math.h>
#include <stdio.h>
#include <string.h>

static void emit(FILE *f, const char *name, int n, double (*fn)(int, int), int b) {
  int i;
  fprintf(f, "%sconst uint32_t %s[%d] = {", strncmp(name, "k_", 2) ? "static " : "", name, n);
  for (i = 0; i < n; i++) {
    if (i % 8 == 0) fprintf(f, "\n ");
    fprintf(f, " %luu,", (unsigned long)llround(fn(i, b)));
  }
  fprintf(f, "\n};\n");
}

static double fexp(int i, int b) { return 65536.0 * exp2(-(double)i / (double)(1 << b)); }
static double fsig(int i, int b) { return 65536.0 / (1.0 + exp(-(double)i * 16.0 / (double)(1 << b))); }
static double frsq(int i, int b) { (void)b; return 262144.0 / sqrt((double)i + 16.5); }

int main(void) {
  FILE *f = stdout;
  int b;
  char nm[32];
  fprintf(f, "/* Generated by tools/gentab.c. Do not edit. */\n#include \"kern.h\"\n\n");
  fprintf(f, "/* k_rsq_lut[i] = round(2^18 / sqrt(i + 16.5)) */\n");
  emit(f, "k_rsq_lut", 48, frsq, 0);
  fprintf(f, "\n");
  fprintf(f, "/* exp_b[i] = round(65536 * 2^(-i / 2^b)), i = 0..2^b */\n");
  for (b = 4; b <= 8; b++) {
    sprintf(nm, "exp_%d", b);
    emit(f, nm, (1 << b) + 1, fexp, b);
  }
  fprintf(f, "\n/* sig_b[i] = round(65536 * sigmoid(16 i / 2^b)), i = 0..2^b */\n");
  for (b = 4; b <= 8; b++) {
    sprintf(nm, "sig_%d", b);
    emit(f, nm, (1 << b) + 1, fsig, b);
  }
  fprintf(f, "\nconst uint32_t *k_exp_lut(int b) {\n  switch (b) {\n");
  for (b = 4; b <= 8; b++) fprintf(f, "  case %d: return exp_%d;\n", b, b);
  fprintf(f, "  default: return 0;\n  }\n}\n");
  fprintf(f, "\nconst uint32_t *k_sig_lut(int b) {\n  switch (b) {\n");
  for (b = 4; b <= 8; b++) fprintf(f, "  case %d: return sig_%d;\n", b, b);
  fprintf(f, "  default: return 0;\n  }\n}\n");
  return 0;
}
